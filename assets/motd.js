/* gabes little server! — live status for the MOTD.
   Reads assets/status-url.js (generated by scripts/update_gist.py --create),
   falls back to assets/status.json, then to the last good copy in localStorage. */

(function () {
  "use strict";

  var REFRESH_MS = 30000;
  var STALE_AFTER = 180;
  var STORAGE_KEY = "gabes-motd-status-v1";
  var DISCORD = "https://discord.gg/BRA5UDjqAE";

  var el = {};
  var lastData = null;

  function $(id) {
    return document.getElementById(id);
  }

  function setText(id, value) {
    var node = el[id] || (el[id] = $(id));
    if (node && node.textContent !== value) {
      node.textContent = value;
    }
  }

  function num(value) {
    var n = Number(value);
    return isFinite(n) && n > 0 ? Math.floor(n) : 0;
  }

  function pad(n) {
    return n < 10 ? "0" + n : String(n);
  }

  function clock(seconds) {
    if (!seconds) return "—";
    var d = new Date(seconds * 1000);
    if (isNaN(d.getTime())) return "—";
    return pad(d.getHours()) + ":" + pad(d.getMinutes());
  }

  function ago(seconds) {
    if (!seconds) return "—";
    var diff = Math.floor(Date.now() / 1000) - seconds;
    if (diff < 0) diff = 0;
    if (diff < 10) return "just now";
    if (diff < 60) return diff + "s ago";
    if (diff < 3600) return Math.floor(diff / 60) + "m ago";
    if (diff < 86400) return Math.floor(diff / 3600) + "h ago";
    return Math.floor(diff / 86400) + "d ago";
  }

  function sources() {
    var out = [];
    var override = null;
    try {
      override = new URLSearchParams(window.location.search).get("status");
    } catch (e) {
      override = null;
    }
    if (override) out.push(override);
    if (window.MOTD_STATUS_URL) out.push(window.MOTD_STATUS_URL);
    return out;
  }

  function cachedStatus() {
    try {
      var cached = localStorage.getItem(STORAGE_KEY);
      if (cached) return JSON.parse(cached);
    } catch (e) {}
    return null;
  }

  function withBuster(url) {
    try {
      var u = new URL(url, window.location.href);
      u.searchParams.set("t", String(Date.now()));
      return u.toString();
    } catch (e) {
      return url;
    }
  }

  function fetchJson(url) {
    return new Promise(function (resolve, reject) {
      var controller = null;
      var timer = null;

      if (window.AbortController) {
        controller = new AbortController();
        timer = setTimeout(function () {
          try { controller.abort(); } catch (e) {}
        }, 6000);
      }

      var options = { cache: "no-store", credentials: "omit" };
      if (controller) options.signal = controller.signal;

      fetch(withBuster(url), options)
        .then(function (res) {
          if (!res.ok) throw new Error("HTTP " + res.status);
          return res.json();
        })
        .then(function (data) {
          if (timer) clearTimeout(timer);
          resolve(data);
        })
        .catch(function (err) {
          if (timer) clearTimeout(timer);
          reject(err);
        });
    });
  }

  function loadStatus() {
    var list = sources();
    var index = 0;

    function next() {
      if (index >= list.length) return Promise.resolve(null);
      var url = list[index++];
      return fetchJson(url).then(function (data) {
        if (data && typeof data === "object") {
          try {
            localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
          } catch (e) {}
          return data;
        }
        return next();
      }).catch(function () {
        return next();
      });
    }

    return next().then(function (data) {
      if (data) return data;
      var cached = cachedStatus();
      if (cached) return cached;
      return fetchJson("assets/status.json").catch(function () {
        return null;
      });
    });
  }

  function markCards(mode) {
    var cards = document.querySelectorAll(".mode-card");
    for (var i = 0; i < cards.length; i++) {
      var card = cards[i];
      var live = card.getAttribute("data-mode") === mode;
      if (live) card.classList.add("is-live");
      else card.classList.remove("is-live");
      var tag = card.querySelector(".mode-live");
      if (tag) tag.hidden = !live;
    }
  }

  function setBadge(kind, label) {
    var badge = el.badge || (el.badge = $("status-badge"));
    if (!badge) return;
    badge.className = "badge badge-" + kind;
    badge.textContent = label;
  }

  function setLiveClass(name) {
    var panel = el.live || (el.live = $("live"));
    if (!panel) return;
    panel.className = "live" + (name ? " is-" + name : "");
  }

  function showConnect(url, address) {
    var btn = el.connect || (el.connect = $("connect-btn"));
    if (btn) {
      if (url) {
        btn.href = url;
        btn.hidden = false;
      } else {
        btn.hidden = true;
      }
    }
    var code = el.code || (el.code = $("connect-code"));
    if (code) {
      code.textContent = address ? "connect " + address : "connect <ip>:<port>";
    }
  }

  function renderUnknown() {
    setBadge("checking", "UNKNOWN");
    setLiveClass("");
    setText("status-mode", "Live status unavailable");
    setText("status-map", "—");
    setText("status-players", "—");
    setText("status-since", "—");
    setText("status-updated", "—");
    setText("status-note", "Could not load the live status. Join the Discord for the current address.");
    setText("foot-status", "status: unavailable");
    showConnect("", "");
    markCards("");
  }

  function render(data) {
    if (!data) {
      renderUnknown();
      return;
    }

    lastData = data;

    var generated = num(data.generated_at);
    var age = generated ? Math.floor(Date.now() / 1000) - generated : Infinity;
    var stale = !generated || age > STALE_AFTER;
    var online = !!data.online;

    var mode = data.mode || "";
    var title = data.mode_pretty || data.version || "Server";
    var map = data.map_pretty || data.map || "—";
    var humans = num(data.players);
    var bots = num(data.bots);
    var max = num(data.maxplayers);
    var players = humans + (bots ? " + " + bots + " bots" : "") + (max ? " / " + max : "");
    var ip = data.ip || "";
    var port = num(data.port);
    var address = ip && port ? ip + ":" + port : "";
    var connect = data.connect || (address ? "steam://connect/" + address + "?appid=440" : "");

    setText("foot-version", data.motd_version || "1.0.0");

    if (!online) {
      setBadge("offline", "OFFLINE");
      setLiveClass("offline");
      setText("status-mode", "Server is offline right now");
      setText("status-map", "—");
      setText("status-players", "0");
      setText("status-since", "—");
      setText("status-updated", ago(generated));
      setText("status-note", "Only one mode runs at a time. Restarts and the next mode are announced in Discord. Last address seen: " + (address || "unknown") + ".");
      setText("foot-status", "offline");
      showConnect("", address);
      markCards("");
      return;
    }

    if (stale) {
      setBadge("stale", "STALE");
      setLiveClass("stale");
      setText("status-note", "This status has not refreshed in " + ago(generated).replace(" ago", "") + ". The server may still be up — that address is the last one seen. Check Discord if it will not connect.");
      setText("foot-status", (data.mode_pretty || "online") + " · stale");
    } else {
      setBadge("live", "LIVE");
      setLiveClass("live");
      setText("status-note", "Random effects are active. Map votes, restarts and bug reports happen in Discord.");
      setText("foot-status", (data.mode_pretty || "online") + " · " + humans + (bots ? " + " + bots : "") + " playing");
    }

    setText("status-mode", title);
    setText("status-map", map);
    setText("status-players", players);
    setText("status-since", clock(num(data.running_since)));
    setText("status-updated", ago(generated));

    var mapNode = el.map || (el.map = $("status-map"));
    if (mapNode) mapNode.title = data.map || "";

    showConnect(connect, address);
    markCards(mode);
  }

  function tick() {
    if (lastData) render(lastData);
  }

  function refresh() {
    loadStatus().then(render).catch(renderUnknown);
  }

  function start() {
    refresh();
    window.setInterval(refresh, REFRESH_MS);
    window.setInterval(tick, 1000);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", start);
  } else {
    start();
  }

  // keep the Discord button working even if the MOTD browser is sandboxed oddly
  document.addEventListener("click", function (event) {
    var target = event.target;
    while (target && target !== document) {
      if (target.tagName === "A" && target.getAttribute("data-discord") === "1") {
        target.href = DISCORD;
      }
      target = target.parentNode;
    }
  });
})();
